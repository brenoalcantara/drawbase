import type { Column, Index, Table } from '../domain/schema-model';
import type { ColumnDefault, Relationship } from '../domain/schema-model';
import {
  autoGeneratedConstraintName,
  formatDecimalType,
  formatIndexColumns,
  formatLiteralDefault,
  formatReferentialAction,
  quoteColumnList,
  quoteQualifiedName,
  resolveIndexColumns,
  resolveRelationshipColumns,
} from './common';
import type { DialectContext, SqlDialect } from './types';

export const mysqlDialect: SqlDialect = {
  name: 'mysql',
  quoteIdentifier,
  formatTableName(table) {
    return quoteQualifiedName(table, quoteIdentifier);
  },
  columnDefinition(column, _table, context) {
    const parts = [quoteIdentifier(column.name), mapColumnType(column, context)];

    if (!column.nullable) {
      parts.push('NOT NULL');
    }

    if (column.type.kind === 'integer' && column.type.autoIncrement) {
      parts.push('AUTO_INCREMENT');
    }

    if (column.unique && !column.primaryKey) {
      parts.push('UNIQUE');
    }

    if (column.default) {
      parts.push(`DEFAULT ${mysqlDialect.defaultExpression(column.default)}`);
    }

    return parts.join(' ');
  },
  primaryKeyConstraint(table, primaryKeyColumns) {
    if (primaryKeyColumns.length === 0) {
      return null;
    }

    return `CONSTRAINT ${quoteIdentifier(autoGeneratedConstraintName('pk', table, primaryKeyColumns))} PRIMARY KEY (${quoteColumnList(primaryKeyColumns, quoteIdentifier)})`;
  },
  uniqueColumnConstraint() {
    return null;
  },
  foreignKeyConstraint(relationship, context) {
    const { localTable, referencedTable, localColumns, referencedColumns } = resolveRelationshipColumns(
      relationship,
      context,
    );
    const constraintName = relationship.name ?? autoGeneratedConstraintName('fk', localTable, localColumns);

    return [
      `CONSTRAINT ${quoteIdentifier(constraintName)} FOREIGN KEY (${quoteColumnList(localColumns, quoteIdentifier)})`,
      `REFERENCES ${mysqlDialect.formatTableName(referencedTable)} (${quoteColumnList(referencedColumns, quoteIdentifier)})`,
      `ON DELETE ${formatReferentialAction(relationship.onDelete)}`,
      `ON UPDATE ${formatReferentialAction(relationship.onUpdate)}`,
    ].join(' ');
  },
  createIndex(table, index, context) {
    const indexColumns = resolveIndexColumns(table, index, context);
    const indexType = createIndexType(index, context);
    const unique = index.unique && index.method !== 'fulltext' ? 'UNIQUE ' : '';

    if (index.where) {
      context.warnings.push({
        code: 'MYSQL_PARTIAL_INDEX_OMITTED',
        message: `MySQL does not support partial indexes in this generator. WHERE clause omitted for index ${index.name}.`,
      });
    }

    return `CREATE ${unique}${indexType}INDEX ${quoteIdentifier(index.name)} ON ${mysqlDialect.formatTableName(table)} (${formatIndexColumns(indexColumns, quoteIdentifier)});`;
  },
  defaultExpression(defaultValue) {
    switch (defaultValue.kind) {
      case 'literal':
        return formatLiteralDefault(defaultValue, { true: 'TRUE', false: 'FALSE' });
      case 'expression':
        return `(${defaultValue.value})`;
      case 'currentTimestamp':
        return 'CURRENT_TIMESTAMP';
      case 'uuid':
        return '(UUID())';
    }
  },
};

function quoteIdentifier(identifier: string) {
  return `\`${identifier.replaceAll('`', '``')}\``;
}

function mapColumnType(column: Column, context: DialectContext) {
  const { type } = column;

  switch (type.kind) {
    case 'integer':
      return type.size === 'small' ? 'SMALLINT' : type.size === 'big' ? 'BIGINT' : 'INT';
    case 'decimal':
      return formatDecimalType(type.precision, type.scale, 'DECIMAL');
    case 'varchar':
      return `VARCHAR(${type.length})`;
    case 'text':
      return 'TEXT';
    case 'boolean':
      return 'BOOLEAN';
    case 'date':
      return 'DATE';
    case 'time':
      return 'TIME';
    case 'timestamp':
      if (type.withTimezone) {
        context.warnings.push({
          code: 'MYSQL_TIMESTAMP_TIMEZONE_OMITTED',
          message: `MySQL TIMESTAMP does not preserve timezone metadata for column ${column.name}.`,
        });
      }

      return 'TIMESTAMP';
    case 'json':
      return 'JSON';
    case 'uuid':
      return 'CHAR(36)';
    case 'binary':
      return 'BLOB';
    case 'custom':
      return type.raw;
  }
}

function createIndexType(index: Index, context: DialectContext) {
  if (!index.method) {
    return '';
  }

  if (index.method === 'fulltext') {
    return 'FULLTEXT ';
  }

  if (index.method === 'gin' || index.method === 'gist') {
    context.warnings.push({
      code: 'MYSQL_INDEX_METHOD_OMITTED',
      message: `MySQL generator omitted unsupported index method ${index.method} for index ${index.name}.`,
    });

    return '';
  }

  return '';
}

