import type {
  Column,
  ColumnDefault,
  Index,
  IndexColumn,
  ProjectSchema,
  ReferentialAction,
  Relationship,
  Table,
} from '../domain/schema-model';
import type { SqlWarning } from '../schemas/sql.schema';
import type { DialectContext, SqlDialect } from './types';

export function createDialectContext(project: ProjectSchema, warnings: SqlWarning[]): DialectContext {
  return {
    project,
    warnings,
    tablesById: new Map(project.tables.map((table) => [table.id, table])),
    columnsByTableId: new Map(
      project.tables.map((table) => [table.id, new Map(table.columns.map((column) => [column.id, column]))]),
    ),
  };
}

export function createStatements(project: ProjectSchema, dialect: SqlDialect, includeComments: boolean) {
  const warnings: SqlWarning[] = [];
  const context = createDialectContext(project, warnings);
  const orderedTables = orderTablesByDependencies(project, warnings);
  const statements: string[] = [];

  if (includeComments) {
    statements.push(createHeader(project, dialect.name));
  }

  orderedTables.forEach((table) => {
    statements.push(createTableStatement(table, project.relationships, dialect, context));
  });

  project.tables.forEach((table) => {
    table.indexes.forEach((index) => {
      const statement = dialect.createIndex(table, index, context);

      if (statement) {
        statements.push(statement);
      }
    });
  });

  return {
    sql: `${statements.filter(Boolean).join('\n\n')}\n`,
    warnings,
  };
}

export function createTableStatement(
  table: Table,
  relationships: Relationship[],
  dialect: SqlDialect,
  context: DialectContext,
) {
  const primaryKeyColumns = table.columns.filter((column) => column.primaryKey);
  const lines = table.columns.map((column) => `  ${dialect.columnDefinition(column, table, context)}`);
  const primaryKey = dialect.primaryKeyConstraint(table, primaryKeyColumns, context);

  if (primaryKey) {
    lines.push(`  ${primaryKey}`);
  }

  relationships
    .filter((relationship) => relationship.localTableId === table.id)
    .forEach((relationship) => {
      lines.push(`  ${dialect.foreignKeyConstraint(relationship, context)}`);
    });

  return `CREATE TABLE ${dialect.formatTableName(table)} (\n${lines.join(',\n')}\n);`;
}

export function createHeader(project: ProjectSchema, dialect: ProjectSchema['dialect']) {
  return [
    '-- Generated by DrawBase',
    `-- Project: ${project.name}`,
    `-- Dialect: ${dialect}`,
    `-- Tables: ${project.tables.length}`,
    `-- Relationships: ${project.relationships.length}`,
  ].join('\n');
}

export function orderTablesByDependencies(project: ProjectSchema, warnings: SqlWarning[]) {
  const dependencies = new Map<string, Set<string>>();
  const dependents = new Map<string, Set<string>>();
  const tablesById = new Map(project.tables.map((table) => [table.id, table]));

  project.tables.forEach((table) => {
    dependencies.set(table.id, new Set());
    dependents.set(table.id, new Set());
  });

  project.relationships.forEach((relationship) => {
    if (!tablesById.has(relationship.localTableId) || !tablesById.has(relationship.referencedTableId)) {
      return;
    }

    if (relationship.localTableId === relationship.referencedTableId) {
      return;
    }

    dependencies.get(relationship.localTableId)?.add(relationship.referencedTableId);
    dependents.get(relationship.referencedTableId)?.add(relationship.localTableId);
  });

  const ready = project.tables.filter((table) => dependencies.get(table.id)?.size === 0).map((table) => table.id);
  const orderedIds: string[] = [];

  while (ready.length > 0) {
    const tableId = ready.shift();

    if (!tableId) {
      continue;
    }

    orderedIds.push(tableId);

    dependents.get(tableId)?.forEach((dependentId) => {
      dependencies.get(dependentId)?.delete(tableId);

      if (dependencies.get(dependentId)?.size === 0 && !orderedIds.includes(dependentId)) {
        ready.push(dependentId);
      }
    });
  }

  if (orderedIds.length !== project.tables.length) {
    warnings.push({
      code: 'CYCLIC_TABLE_DEPENDENCY',
      message: 'One or more foreign key cycles were detected. SQL was emitted in project order for cyclic tables.',
    });
  }

  const orderedSet = new Set(orderedIds);
  return [
    ...orderedIds.map((tableId) => tablesById.get(tableId)).filter((table): table is Table => Boolean(table)),
    ...project.tables.filter((table) => !orderedSet.has(table.id)),
  ];
}

export function quoteQualifiedName(table: Table, quoteIdentifier: (identifier: string) => string) {
  return table.schema
    ? `${quoteIdentifier(table.schema)}.${quoteIdentifier(table.name)}`
    : quoteIdentifier(table.name);
}

export function quoteColumnList(columns: Column[], quoteIdentifier: (identifier: string) => string) {
  return columns.map((column) => quoteIdentifier(column.name)).join(', ');
}

export function resolveRelationshipColumns(relationship: Relationship, context: DialectContext) {
  const localTable = context.tablesById.get(relationship.localTableId);
  const referencedTable = context.tablesById.get(relationship.referencedTableId);
  const localColumnsById = context.columnsByTableId.get(relationship.localTableId);
  const referencedColumnsById = context.columnsByTableId.get(relationship.referencedTableId);

  if (!localTable || !referencedTable || !localColumnsById || !referencedColumnsById) {
    throw new Error(`Relationship ${relationship.id} references unknown tables.`);
  }

  const localColumns = relationship.localColumnIds.map((columnId) => {
    const column = localColumnsById.get(columnId);

    if (!column) {
      throw new Error(`Relationship ${relationship.id} references unknown local column ${columnId}.`);
    }

    return column;
  });

  const referencedColumns = relationship.referencedColumnIds.map((columnId) => {
    const column = referencedColumnsById.get(columnId);

    if (!column) {
      throw new Error(`Relationship ${relationship.id} references unknown referenced column ${columnId}.`);
    }

    return column;
  });

  return {
    localTable,
    referencedTable,
    localColumns,
    referencedColumns,
  };
}

export function resolveIndexColumns(table: Table, index: Index, context: DialectContext) {
  const columnsById = context.columnsByTableId.get(table.id);

  return index.columns.map((indexColumn) => {
    const column = columnsById?.get(indexColumn.columnId);

    if (!column) {
      throw new Error(`Index ${index.id} references unknown column ${indexColumn.columnId}.`);
    }

    return {
      column,
      order: indexColumn.order,
    };
  });
}

export function formatIndexColumns(
  indexColumns: Array<{ column: Column; order: IndexColumn['order'] }>,
  quoteIdentifier: (identifier: string) => string,
) {
  return indexColumns.map(({ column, order }) => `${quoteIdentifier(column.name)} ${order.toUpperCase()}`).join(', ');
}

export function formatReferentialAction(action: ReferentialAction | undefined) {
  switch (action) {
    case 'cascade':
      return 'CASCADE';
    case 'restrict':
      return 'RESTRICT';
    case 'setNull':
      return 'SET NULL';
    case 'setDefault':
      return 'SET DEFAULT';
    case 'noAction':
    case undefined:
      return 'NO ACTION';
  }
}

export function formatDecimalType(precision: number | undefined, scale: number | undefined, name: string) {
  if (precision !== undefined && scale !== undefined) {
    return `${name}(${precision}, ${scale})`;
  }

  if (precision !== undefined) {
    return `${name}(${precision})`;
  }

  return name;
}

export function formatLiteralDefault(value: ColumnDefault & { kind: 'literal' }, booleanValues: { true: string; false: string }) {
  if (value.value === null) {
    return 'NULL';
  }

  if (typeof value.value === 'number') {
    return `${value.value}`;
  }

  if (typeof value.value === 'boolean') {
    return value.value ? booleanValues.true : booleanValues.false;
  }

  return `'${value.value.replaceAll("'", "''")}'`;
}

export function autoGeneratedConstraintName(prefix: string, table: Table, columns: Column[]) {
  return `${prefix}_${table.name}_${columns.map((column) => column.name).join('_')}`;
}

