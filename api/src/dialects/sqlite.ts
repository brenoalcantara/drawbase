import type { Column, Index, Table } from '../domain/schema-model';
import {
  autoGeneratedConstraintName,
  formatDecimalType,
  formatIndexColumns,
  formatLiteralDefault,
  formatReferentialAction,
  quoteColumnList,
  quoteQualifiedName,
  resolveIndexColumns,
  resolveRelationshipColumns,
} from './common';
import type { DialectContext, SqlDialect } from './types';

export const sqliteDialect: SqlDialect = {
  name: 'sqlite',
  quoteIdentifier,
  formatTableName(table) {
    return quoteQualifiedName(table, quoteIdentifier);
  },
  columnDefinition(column, table, context) {
    const inlinePrimaryKey = isInlineAutoIncrementPrimaryKey(column, table);
    const parts = [quoteIdentifier(column.name), mapColumnType(column, context)];

    if (inlinePrimaryKey) {
      parts.push('PRIMARY KEY AUTOINCREMENT');
    }

    if (!column.nullable && !inlinePrimaryKey) {
      parts.push('NOT NULL');
    }

    if (column.unique && !column.primaryKey) {
      parts.push('UNIQUE');
    }

    if (column.default) {
      parts.push(`DEFAULT ${sqliteDialect.defaultExpression(column.default)}`);
    }

    return parts.join(' ');
  },
  primaryKeyConstraint(table, primaryKeyColumns) {
    if (primaryKeyColumns.length === 0 || primaryKeyColumns.some((column) => isInlineAutoIncrementPrimaryKey(column, table))) {
      return null;
    }

    return `CONSTRAINT ${quoteIdentifier(autoGeneratedConstraintName('pk', table, primaryKeyColumns))} PRIMARY KEY (${quoteColumnList(primaryKeyColumns, quoteIdentifier)})`;
  },
  uniqueColumnConstraint() {
    return null;
  },
  foreignKeyConstraint(relationship, context) {
    const { localTable, referencedTable, localColumns, referencedColumns } = resolveRelationshipColumns(
      relationship,
      context,
    );
    const constraintName = relationship.name ?? autoGeneratedConstraintName('fk', localTable, localColumns);

    return [
      `CONSTRAINT ${quoteIdentifier(constraintName)} FOREIGN KEY (${quoteColumnList(localColumns, quoteIdentifier)})`,
      `REFERENCES ${sqliteDialect.formatTableName(referencedTable)} (${quoteColumnList(referencedColumns, quoteIdentifier)})`,
      `ON DELETE ${formatReferentialAction(relationship.onDelete)}`,
      `ON UPDATE ${formatReferentialAction(relationship.onUpdate)}`,
    ].join(' ');
  },
  createIndex(table, index, context) {
    const indexColumns = resolveIndexColumns(table, index, context);
    const unique = index.unique ? 'UNIQUE ' : '';
    const where = index.where ? ` WHERE ${index.where}` : '';

    if (index.method) {
      context.warnings.push({
        code: 'SQLITE_INDEX_METHOD_OMITTED',
        message: `SQLite does not support explicit index methods. Method ${index.method} omitted for index ${index.name}.`,
      });
    }

    return `CREATE ${unique}INDEX ${quoteIdentifier(index.name)} ON ${sqliteDialect.formatTableName(table)} (${formatIndexColumns(indexColumns, quoteIdentifier)})${where};`;
  },
  defaultExpression(defaultValue) {
    switch (defaultValue.kind) {
      case 'literal':
        return formatLiteralDefault(defaultValue, { true: '1', false: '0' });
      case 'expression':
        return `(${defaultValue.value})`;
      case 'currentTimestamp':
        return 'CURRENT_TIMESTAMP';
      case 'uuid':
        return "(lower(hex(randomblob(4))) || '-' || lower(hex(randomblob(2))) || '-4' || substr(lower(hex(randomblob(2))), 2) || '-' || substr('89ab', abs(random()) % 4 + 1, 1) || substr(lower(hex(randomblob(2))), 2) || '-' || lower(hex(randomblob(6))))";
    }
  },
};

function quoteIdentifier(identifier: string) {
  return `"${identifier.replaceAll('"', '""')}"`;
}

function mapColumnType(column: Column, context: DialectContext) {
  const { type } = column;

  switch (type.kind) {
    case 'integer':
      return 'INTEGER';
    case 'decimal':
      return formatDecimalType(type.precision, type.scale, 'NUMERIC');
    case 'varchar':
    case 'text':
      return 'TEXT';
    case 'boolean':
      return 'INTEGER';
    case 'date':
    case 'time':
      return 'TEXT';
    case 'timestamp':
      if (type.withTimezone) {
        context.warnings.push({
          code: 'SQLITE_TIMESTAMP_TIMEZONE_OMITTED',
          message: `SQLite stores timestamp values as TEXT in this generator. Timezone metadata omitted for column ${column.name}.`,
        });
      }

      return 'TEXT';
    case 'json':
      return 'TEXT';
    case 'uuid':
      return 'TEXT';
    case 'binary':
      return 'BLOB';
    case 'custom':
      return type.raw;
  }
}

function isInlineAutoIncrementPrimaryKey(column: Column, table: Table) {
  const primaryKeyColumns = table.columns.filter((candidate) => candidate.primaryKey);

  return (
    primaryKeyColumns.length === 1 &&
    primaryKeyColumns[0]?.id === column.id &&
    column.type.kind === 'integer' &&
    column.type.autoIncrement
  );
}

