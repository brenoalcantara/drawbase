import type { Column, ColumnDefault, Index, Relationship, Table } from '../domain/schema-model';
import {
  autoGeneratedConstraintName,
  formatDecimalType,
  formatIndexColumns,
  formatLiteralDefault,
  formatReferentialAction,
  quoteColumnList,
  quoteQualifiedName,
  resolveIndexColumns,
  resolveRelationshipColumns,
} from './common';
import type { DialectContext, SqlDialect } from './types';

export const postgresDialect: SqlDialect = {
  name: 'postgres',
  quoteIdentifier,
  formatTableName(table) {
    return quoteQualifiedName(table, quoteIdentifier);
  },
  columnDefinition(column) {
    const parts = [quoteIdentifier(column.name), mapColumnType(column)];

    if (!column.nullable) {
      parts.push('NOT NULL');
    }

    if (column.unique && !column.primaryKey) {
      parts.push('UNIQUE');
    }

    if (column.default) {
      parts.push(`DEFAULT ${postgresDialect.defaultExpression(column.default)}`);
    }

    return parts.join(' ');
  },
  primaryKeyConstraint(table, primaryKeyColumns) {
    if (primaryKeyColumns.length === 0) {
      return null;
    }

    return `CONSTRAINT ${quoteIdentifier(autoGeneratedConstraintName('pk', table, primaryKeyColumns))} PRIMARY KEY (${quoteColumnList(primaryKeyColumns, quoteIdentifier)})`;
  },
  uniqueColumnConstraint() {
    return null;
  },
  foreignKeyConstraint(relationship, context) {
    const { localTable, referencedTable, localColumns, referencedColumns } = resolveRelationshipColumns(
      relationship,
      context,
    );
    const constraintName = relationship.name ?? autoGeneratedConstraintName('fk', localTable, localColumns);

    return [
      `CONSTRAINT ${quoteIdentifier(constraintName)} FOREIGN KEY (${quoteColumnList(localColumns, quoteIdentifier)})`,
      `REFERENCES ${postgresDialect.formatTableName(referencedTable)} (${quoteColumnList(referencedColumns, quoteIdentifier)})`,
      `ON DELETE ${formatReferentialAction(relationship.onDelete)}`,
      `ON UPDATE ${formatReferentialAction(relationship.onUpdate)}`,
    ].join(' ');
  },
  createIndex(table, index, context) {
    const indexColumns = resolveIndexColumns(table, index, context);
    const unique = index.unique ? 'UNIQUE ' : '';
    const method = index.method ? ` USING ${index.method.toUpperCase()}` : '';
    const where = index.where ? ` WHERE ${index.where}` : '';

    return `CREATE ${unique}INDEX ${quoteIdentifier(index.name)} ON ${postgresDialect.formatTableName(table)}${method} (${formatIndexColumns(indexColumns, quoteIdentifier)})${where};`;
  },
  defaultExpression(defaultValue) {
    switch (defaultValue.kind) {
      case 'literal':
        return formatLiteralDefault(defaultValue, { true: 'TRUE', false: 'FALSE' });
      case 'expression':
        return defaultValue.value;
      case 'currentTimestamp':
        return 'CURRENT_TIMESTAMP';
      case 'uuid':
        return 'gen_random_uuid()';
    }
  },
};

function quoteIdentifier(identifier: string) {
  return `"${identifier.replaceAll('"', '""')}"`;
}

function mapColumnType(column: Column) {
  const { type } = column;

  switch (type.kind) {
    case 'integer':
      if (type.autoIncrement) {
        return type.size === 'small' ? 'SMALLSERIAL' : type.size === 'big' ? 'BIGSERIAL' : 'SERIAL';
      }

      return type.size === 'small' ? 'SMALLINT' : type.size === 'big' ? 'BIGINT' : 'INTEGER';
    case 'decimal':
      return formatDecimalType(type.precision, type.scale, 'NUMERIC');
    case 'varchar':
      return `VARCHAR(${type.length})`;
    case 'text':
      return 'TEXT';
    case 'boolean':
      return 'BOOLEAN';
    case 'date':
      return 'DATE';
    case 'time':
      return 'TIME';
    case 'timestamp':
      return type.withTimezone ? 'TIMESTAMP WITH TIME ZONE' : 'TIMESTAMP';
    case 'json':
      return 'JSONB';
    case 'uuid':
      return 'UUID';
    case 'binary':
      return 'BYTEA';
    case 'custom':
      return type.raw;
  }
}

